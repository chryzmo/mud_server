#!/usr/bin/env bash
# Regenerate deploy/cloudflare-ips.caddy from Cloudflare's published ranges.
#
# Caddy only believes the CF-Connecting-IP header from a connection that really comes
# from Cloudflare, so the list must be current. Cloudflare changes it rarely, but not
# never: run this before an event, review the diff, and deploy. The ranges are
# committed (not fetched at build time) so a build is reproducible and a Cloudflare
# outage cannot break a deploy.
#
#   deploy/update-cloudflare-ips.sh            # rewrite the file
#   deploy/update-cloudflare-ips.sh --check    # exit 1 if the committed file is out of date
set -euo pipefail
cd "$(dirname "$0")"

mode="write"
case "${1:-}" in
	"") ;;
	--check) mode="check" ;;
	*) echo "usage: $0 [--check]" >&2; exit 2 ;;
esac

fetch() { curl -fsS --max-time 20 "https://www.cloudflare.com/$1"; }
v4="$(fetch ips-v4)"
v6="$(fetch ips-v6)"

# Refuse anything that is not a plain list of CIDRs, and a suspiciously short list.
valid='^[0-9a-fA-F:.]+/[0-9]+$'
ranges=()
while IFS= read -r line; do
	line="${line//$'\r'/}"
	[ -z "$line" ] && continue
	[[ "$line" =~ $valid ]] || { echo "unexpected line from Cloudflare: $line" >&2; exit 1; }
	ranges+=("$line")
done <<< "$v4"$'\n'"$v6"
[ "${#ranges[@]}" -ge 10 ] || { echo "only ${#ranges[@]} ranges came back; refusing to write" >&2; exit 1; }

out="$(
	echo "# Cloudflare's published IP ranges, from https://www.cloudflare.com/ips-v4 and /ips-v6."
	echo "# Generated by deploy/update-cloudflare-ips.sh; do not edit by hand."
	echo "# Caddy trusts CF-Connecting-IP only from these (see deploy/Caddyfile)."
	echo "(cloudflare_ips) {"
	printf '\ttrusted_proxies static'
	for r in "${ranges[@]}"; do printf ' %s' "$r"; done
	echo
	echo "}"
)"

if [ "$mode" = check ]; then
	if [ "$out" = "$(cat cloudflare-ips.caddy)" ]; then
		echo "cloudflare-ips.caddy is current (${#ranges[@]} ranges)"
	else
		echo "cloudflare-ips.caddy is out of date; run deploy/update-cloudflare-ips.sh" >&2
		exit 1
	fi
else
	printf '%s\n' "$out" > cloudflare-ips.caddy
	echo "wrote cloudflare-ips.caddy (${#ranges[@]} ranges)"
fi
